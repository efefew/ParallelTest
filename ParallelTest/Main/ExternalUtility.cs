/// <summary>
/// Внешний энергоноситель (утилита)
/// </summary>
public class ExternalUtility
{
    /// <summary>
    /// Имя утилиты
    /// </summary>
    public string Name;
    /// <summary>
    /// Температура входная
    /// </summary>
    public double TimperatureIn;
    /// <summary>
    /// Температура выходная
    /// </summary>
    public double TemperatureOut;
    /// <summary>
    /// Коэффициент теплопередачи
    /// </summary>
    public double HeatTransferCoefficient;
    /// <summary>
    /// Стоимость
    /// </summary>
    public double Cost;
}